def make_key(text):
    t = text.strip()
    t = re.sub(r'[^\w\s-]', '', t)
    t = re.sub(r'\s+', '_', t)
    t = t.lower()[:50].strip('_')
    return t or "text"

def get_en(text):
    return EN_MAP.get(text, text)

def ensure_key(text):
    k = make_key(text)
    if k in seen_keys:
        i = 2
        while f"{k}_{i}" in seen_keys:
            i += 1
        k = f"{k}_{i}"
    seen_keys.add(k)
    return k

def translate_file(path, relname):
    with open(path, "r", encoding="utf-8") as f:
        original = f.read()

    result_parts = []
    last_end = 0

    for m in re.finditer(r'(?s)(<script[^>]*>)(.*?)(</script>)', original):
        html_chunk = original[last_end:m.start()]
        result_parts.append(process_html(html_chunk, relname))
        result_parts.append(original[m.start():m.end()])
        last_end = m.end()

    result_parts.append(process_html(original[last_end:], relname))
    result = "".join(result_parts)

    with open(path, "w", encoding="utf-8") as f:
        f.write(result)

def process_html(html, relname):
    def replacer(m):
        full = m.group(0)
        text = m.group(1)

        # Skip if no Chinese
        if not re.search(r'[\u4e00-\u9fff]', text):
            return full

        # Skip if already translated
        if '{{t' in text:
            return full

        # Skip if contains Go template expressions (complex cases)
        if '{{' in text and '}}' in text:
            return full

        # Skip pure template code
        stripped = text.strip()
        if stripped.startswith('{{') or stripped.endswith('}}'):
            return full

        # Skip excluded
        if stripped in EXCLUDE_SET:
            return full

        # Skip country codes and short codes that look like options
        if re.match(r'^[A-Z]{2}$', stripped):
            return full

        # Determine category by looking at surrounding context (the 30 chars before > and 30 after <)
        pos = m.start()
        ctx_before = html[max(0, pos-30):pos]
        ctx_after = html[m.end():m.end()+30]
        ctx = (ctx_before + ctx_after).lower()

        cat = "ui"
        if "sidebar" in ctx or "nav" in ctx or relname == "layout.html":
            cat = "nav"
        elif "card-title" in ctx or "h1" in ctx or "h2" in ctx or "h3" in ctx:
            cat = "title"
        elif "stat-label" in ctx:
            cat = "stat"
        elif "btn" in ctx:
            cat = "action"
        elif "th" in ctx:
            cat = "table"
        elif "label" in ctx or "form-label" in ctx:
            cat = "form"
        elif "option" in ctx:
            cat = "option"
        elif "badge" in ctx:
            cat = "status"
        elif "pagination" in ctx:
            cat = "pagination"
        elif "modal-title" in ctx:
            cat = "modal"
        elif "placeholder" in ctx:
            cat = "placeholder"
        elif "empty" in ctx or "暂无" in stripped or "加载中" in stripped:
            cat = "empty"

        key = ensure_key(f"{cat}_{stripped}")
        if key not in zh and key not in en and key not in new_trans:
            new_trans[key] = {"zh": stripped, "en": get_en(stripped)}

        return f">{{{{t \"{key}\"}}}}<"

    # Single capture group: the entire text between > and <
    html = re.sub(r'>([^<]*[\u4e00-\u9fff][^<]*)<', replacer, html)
    return html

# Run
files = sorted(glob.glob(os.path.join(TPL_DIR, "*.html")))
for path in files:
    translate_file(path, os.path.basename(path))

for subdir in ["enterprise", "super"]:
    subpath = os.path.join(TPL_DIR, subdir)
    if os.path.isdir(subpath):
        for path in sorted(glob.glob(os.path.join(subpath, "*.html"))):
            translate_file(path, os.path.basename(path))

# Merge
for k, v in new_trans.items():
    zh[k] = v["zh"]
    en[k] = v["en"]

